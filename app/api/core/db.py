# Dipertahankan agar kode lama yang mengimpor SCHEMA tidak rusak.
SCHEMA = SCHEMA_POSTGRES if USE_POSTGRES else SCHEMA_SQLITE


# ------------------------------------------------------------------
# ADAPTER POSTGRES
# ------------------------------------------------------------------

class Row:
    """Baris hasil query yang bisa diakses lewat nama kolom maupun indeks
    (meniru sqlite3.Row), termasuk `dict(row)` dan `row.keys()`."""

    __slots__ = ("_cols", "_vals")

    def __init__(self, cols, vals):
        self._cols = cols
        self._vals = tuple(vals)

    def __getitem__(self, key):
        if isinstance(key, str):
            try:
                return self._vals[self._cols.index(key)]
            except ValueError:
                raise IndexError(f"No item with that key: {key}") from None
        return self._vals[key]

    def keys(self):
        return list(self._cols)

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)


_INSERT_RE = re.compile(r"^\s*INSERT\s+INTO\b", re.IGNORECASE)
_RETURNING_RE = re.compile(r"\bRETURNING\b", re.IGNORECASE)


def _to_pg_sql(sql: str) -> str:
    """Placeholder '?' (gaya SQLite) -> '%s' (gaya psycopg).

    Tanda '%' literal di SQL harus digandakan agar tidak dianggap placeholder.
    Tidak ada literal berisi '?' di kode aplikasi, jadi penggantian langsung aman.
    """
    return sql.replace("%", "%%").replace("?", "%s")


class _PgCursor:
    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self._lastrowid = lastrowid

    def _cols(self):
        return [d.name for d in (self._cur.description or [])]

    def fetchone(self):
        r = self._cur.fetchone()
        return None if r is None else Row(self._cols(), r)

    def fetchall(self):
        cols = self._cols()
        return [Row(cols, r) for r in self._cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())

    @property
    def lastrowid(self):
        return self._lastrowid

    @property
    def rowcount(self):
        return self._cur.rowcount


class _PgConnection:
    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql, params=()):
        is_insert = bool(_INSERT_RE.match(sql)) and not _RETURNING_RE.search(sql)
        pg_sql = _to_pg_sql(sql)
        if is_insert:
            # Pengganti cursor.lastrowid milik SQLite.
            pg_sql = pg_sql.rstrip().rstrip(";") + " RETURNING id"
        cur = self._conn.execute(pg_sql, tuple(params))
        lastrowid = cur.fetchone()[0] if is_insert else None
        return _PgCursor(cur, lastrowid)

    def executescript(self, script):
        # Tanpa parameter, psycopg boleh menjalankan beberapa statement sekaligus.
        self._conn.execute(script)


# ------------------------------------------------------------------
# KONEKSI
# ------------------------------------------------------------------

_pool = None
_pool_lock = threading.Lock()


def _get_pool():
    global _pool
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                from psycopg_pool import ConnectionPool

                _pool = ConnectionPool(
                    DATABASE_URL,
                    min_size=1,
                    max_size=POOL_MAX_SIZE,
                    # prepare_threshold=None: aman untuk pooler PgBouncer
                    # (mode transaction) seperti milik Supabase / Neon.
                    kwargs={"prepare_threshold": None},
                    # Koneksi yang diputus server (Neon/Render idle) dibuang,
                    # lalu diganti otomatis sebelum dipakai.
                    check=ConnectionPool.check_connection,
                    open=True,
                )
                # Skrip CLI (manage.py dst.) tidak punya shutdown hook;
                # tanpa ini muncul peringatan "couldn't stop thread".
                atexit.register(close_pool)
    return _pool


def close_pool() -> None:
    """Tutup pool koneksi (dipanggil saat server berhenti)."""
    global _pool
    if _pool is not None:
        _pool.close()
        _pool = None


@contextmanager
def connect():
    if ON_VERCEL and not USE_POSTGRES:
        raise RuntimeError(
            "DATABASE_URL belum diset di Vercel (Project Settings > Environment "
            "Variables). SQLite tidak bisa dipakai karena filesystem Vercel read-only."
        )

    if USE_POSTGRES and ON_VERCEL:
        import psycopg

        # Satu koneksi per invokasi. Pakai connection string "Transaction pooler"
        # Supabase (port 6543) agar jumlah koneksi tidak membengkak.
        raw = psycopg.connect(DATABASE_URL, prepare_threshold=None, connect_timeout=10)
        try:
            yield _PgConnection(raw)
            raw.commit()
        except Exception:
            raw.rollback()
            raise
        finally:
            raw.close()
        return

    if USE_POSTGRES:
        # Context manager pool: commit bila sukses, rollback bila error.
        with _get_pool().connection() as raw:
            yield _PgConnection(raw)
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    with connect() as conn:
        conn.executescript(SCHEMA)


def describe() -> str:
    """Deskripsi singkat database yang sedang dipakai (tanpa membocorkan sandi)."""
    if USE_POSTGRES:
        return "PostgreSQL @ " + re.sub(r"//[^@/]*@", "//***@", DATABASE_URL)
    return f"SQLite file {DB_PATH.resolve()}"
