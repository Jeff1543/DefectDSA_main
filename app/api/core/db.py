"""
Lapisan database.

Mode penyimpanan:
- Cloud / produksi : PostgreSQL, aktif bila DATABASE_URL diset
                     (Neon, Supabase, Render Postgres, Railway, dst.).
- Lokal (default)  : file SQLite di APP_DB_PATH (tanpa dependensi tambahan);
                     dipakai untuk pengembangan dan test.

Kode aplikasi menulis SQL dengan placeholder `?` dan membaca hasil lewat
nama kolom (`row["email"]`) atau indeks (`row[0]`). Lapisan ini menerjemahkan
semuanya ke psycopg (Postgres) sehingga service tidak perlu tahu DB mana
yang dipakai.

Menyimpan: akun pengguna, riwayat analisis ragam, dan respons kuesioner.
Dataset mentah yang diunggah TIDAK disimpan di sini (tetap sementara di memori).
"""

import atexit
import os
import re
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path
from urllib.parse import urlparse

from app.api.core.config import DATA_DIR

DB_PATH = Path(os.environ.get("APP_DB_PATH", DATA_DIR / "app.db"))

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
# Sebagian penyedia (Heroku/Render lama) memberi skema "postgres://".
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = "postgresql://" + DATABASE_URL[len("postgres://"):]


def _require_ssl(url: str) -> str:
    """Paksa koneksi terenkripsi ke server non-lokal bila URL belum menyebut sslmode."""
    if not url or "sslmode=" in url:
        return url
    host = urlparse(url).hostname or ""
    if host in ("", "localhost", "127.0.0.1", "::1") or host.startswith("/"):
        return url
    return url + ("&" if "?" in url else "?") + "sslmode=require"


DATABASE_URL = _require_ssl(DATABASE_URL)
USE_POSTGRES = bool(DATABASE_URL)

# Vercel/serverless: filesystem read-only dan proses dibekukan antar request,
# jadi tidak memakai SQLite maupun pool koneksi berumur panjang.
ON_VERCEL = bool(os.environ.get("VERCEL"))

POOL_MAX_SIZE = int(os.environ.get("DB_POOL_MAX", "5"))


# ------------------------------------------------------------------
# SKEMA
# ------------------------------------------------------------------
# created_at sengaja tetap TEXT (ISO-8601 UTC) dan kolom JSON tetap TEXT,
# supaya perilaku aplikasi identik di kedua database.

